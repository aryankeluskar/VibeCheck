import { iwsdkDev } from '@iwsdk/vite-plugin-dev';
import { defineConfig } from 'vite';

// The mirror app is served by the Next.js app at /xr/ (built into
// ../public/xr). In dev, /api/* is proxied to the Next dev server.
const NEXT_DEV_URL = process.env.NEXT_DEV_URL ?? 'http://localhost:3100';

export default defineConfig({
  plugins: [iwsdkDev()],
  server: {
    host: '0.0.0.0',
    port: 8081,
    open: false,
    // Shared engine modules live in ../app (pose, compare, coach).
    fs: { allow: ['..'] },
    proxy: { '/api': { target: NEXT_DEV_URL, changeOrigin: true } },
  },
  build: {
    outDir: '../public/xr',
    emptyOutDir: true,
    sourcemap: false,
    target: 'esnext',
    rollupOptions: { input: './index.html' },
  },
  esbuild: { target: 'esnext' },
  // @drawcall/uikitml otherwise pulls a second three/@pmndrs/uikit graph
  // (three@0.185 vs app super-three@0.181). Duplicate Component classes break
  // instanceof checks → "Only pmndrs/uikit components can be added as children".
  resolve: {
    dedupe: [
      'three',
      '@pmndrs/uikit',
      '@pmndrs/uikit-horizon',
      '@pmndrs/uikit-lucide',
    ],
  },
  optimizeDeps: {
    exclude: ['@babylonjs/havok'],
    include: [
      'three',
      '@pmndrs/uikit',
      '@pmndrs/uikit-horizon',
      '@pmndrs/uikit-lucide',
      '@drawcall/uikitml',
    ],
    esbuildOptions: { target: 'esnext' },
  },
  publicDir: 'public',
  base: '/xr/',
});
